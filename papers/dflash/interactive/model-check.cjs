const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict'),path=require('node:path');
const sandbox={window:{}};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'model.js'),'utf8'),sandbox);
const m=sandbox.window.DFlashModel;
assert.equal(m.prefix([1,2,9,4],[1,2,3,4]),2);
assert.equal(m.prefix([1,2,3],[1,2,3]),3);
assert.equal(m.prefix([9,2,3],[1,2,3]),0);
assert.equal(m.expectedLength([1,1,1]),4);
assert.equal(m.expectedLength([0,1,1]),1);
assert.ok(Math.abs(m.expectedLength([.8,.8,.8,.8])-3.3616)<1e-12);
assert.equal(m.lossWeight(1,7),1);
assert.ok(Math.abs(m.lossWeight(8,7)-Math.exp(-1))<1e-12);
const x=m.memory({B:1,S:2048,D:2048,F:5,L:5,G:8,d:128,b:2});
assert.equal(x.projection,41943040);
assert.equal(x.input,41943040);
assert.equal(x.output,8388608);
assert.equal(x.kv,41943040);
assert.equal(m.memory({B:8,S:32768,D:2048,F:5,L:5,G:8,d:128,b:2}).kv,5*2**30);
assert.equal(m.speedup(10,2,12,7),5);
console.log('PASS prefix survival, weighted loss, memory scaling and analytical latency');
