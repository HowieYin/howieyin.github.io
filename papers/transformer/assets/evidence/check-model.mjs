import assert from "node:assert/strict";
import { existsSync } from "node:fs";
const path = new URL("../model.mjs", import.meta.url);
assert.ok(existsSync(path), "Attention/KV educational model is not implemented yet");
const { attention, kvBytes, blockFlops } = await import(path);
const near = (a, b) => assert.ok(Math.abs(a-b) < 1e-9, `${a} != ${b}`);
const Q = [[1,0],[0,1]], K = [[1,0],[0,1]], V = [[10,0],[0,20]];
const p = Math.exp(1/Math.sqrt(2))/(Math.exp(1/Math.sqrt(2))+1);
const full = attention(Q,K,V,{causal:false,scaled:true});
near(full.weights[0][0],p); near(full.output[0][0],10*p); near(full.output[0][1],20*(1-p));
const causal = attention(Q,K,V,{causal:true,scaled:true});
assert.deepEqual(causal.weights[0],[1,0]); assert.deepEqual(causal.output[0],[10,0]);
near(causal.weights[1].reduce((a,b)=>a+b),1);
const huge = attention([[1000,0]],[[1000,0],[0,1000]],V,{causal:false,scaled:true});
assert.ok(huge.output.flat().every(Number.isFinite));
assert.equal(kvBytes({layers:6,batch:1,tokens:4096,heads:8,dim:64,bytes:2}),48*1024**2);
assert.equal(kvBytes({layers:6,batch:1,tokens:512,heads:8,dim:64,bytes:2}),6*1024**2);
assert.equal(kvBytes({layers:6,batch:1,tokens:4096,heads:1,dim:64,bytes:2}),6*1024**2);
const cost=blockFlops(512,512,2048);
assert.equal(cost.projection,1073741824); assert.equal(cost.mixing,536870912); assert.equal(cost.ffn,2147483648);
console.log(JSON.stringify({checks:11,causalFirstRow:causal.weights[0],toyProbability:p,baseSelfMiB:48,crossMiB:6,cost},null,2));
